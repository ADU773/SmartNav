const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { randomUUID, randomBytes } = require("node:crypto");
const mongoose = require("mongoose");
const sharp = require("sharp");
const { MongoMemoryReplSet } = require("mongodb-memory-server");
const {installTestEnv,createTestUser}=require("./helpers/auth.cjs");
test("private source, scan, review, baked publication, and replacement gate", {timeout:180000}, async t=>{
    const env=installTestEnv();
    const db=await MongoMemoryReplSet.create({replSet:{count:1},binary:{version:"8.0.17"}});
    t.after(()=>db.stop());
    await mongoose.connect(db.getUri());
    t.after(()=>mongoose.disconnect());
    const Project=require("../models/Project"), Scene=require("../models/Scene"), Asset=require("../models/Asset");
    const owner=await createTestUser(), other=await createTestUser();
    const project=await Project.create({name:"Test tour",ownerId:owner.user._id});
    const filename=randomUUID()+".png", uri="/uploads/"+filename;
    const file=require("../services/fileCleanup").resolveUploadFile(filename);
    await sharp(randomBytes(200*100*3),{raw:{width:200,height:100,channels:3}}).png().toFile(file);
    t.after(()=>fs.unlink(file));
    const asset=await Asset.create({projectId:project.id,path:uri,filename});
    const scene=await Scene.create({projectId:project.id,name:"Test room",image:uri,objectScan:{image:uri,viewsScanned:12}});
    const app=require("../app").createApp(env);
    const server=app.listen(0,"127.0.0.1");
    await new Promise(r=>server.once("listening",r));
    t.after(()=>new Promise(r=>server.close(r)));
    const url="http://127.0.0.1:"+server.address().port;
    const post=(p,data,headers=owner.headers)=>fetch(url+p,{method:"POST",headers:{...headers,"Content-Type":"application/json"},body:JSON.stringify(data)});
    assert.equal((await fetch(url+uri)).status,403);
    const list=await (await fetch(url+"/api/projects/"+project.id+"/privacy",{headers:owner.headers})).json();
    assert.equal((await fetch(url+list.mediaLinks[uri])).status,200);
    const publish="/api/projects/"+project.id+"/publish", review="/api/privacy/"+asset.id;
    assert.equal((await post(publish,{})).status,409);
    assert.equal((await post(review+"/scan",{},other.headers)).status,404);
    assert.equal((await post(review+"/scan",{})).status,200);
    assert.equal((await post(review+"/approve",{masks:[{x:-1,y:0,w:1,h:1}]})).status,400);
    assert.equal((await post(review+"/approve",{masks:[{x:0,y:0,w:1,h:1}]})).status,200);
    const approved=await Asset.findById(asset.id);
    const root=require("../services/privacy").root;
    for(const name of [approved.privacy.version,approved.privacy.thumb]) t.after(()=>fs.unlink(path.join(root,name)));
    const result=await (await post(publish,{})).json();
    const share="/api/published/"+result.data.shareToken;
    const published=await (await fetch(url+share)).json();
    assert.ok(!JSON.stringify(published).includes(filename));
    for(const media of [published.data.scenes[0].image,published.data.scenes[0].thumbnailPath]){
        const response=await fetch(url+media);
        assert.equal(response.status,200);
        const stats=await sharp(Buffer.from(await response.arrayBuffer())).stats();
        assert.ok(stats.channels.every(c=>c.stdev<12),"full-image mask suppresses original detail");
    }
    await Scene.updateOne({_id:scene.id},{$set:{image:"/uploads/unreviewed.jpg"}});
    assert.equal((await fetch(url+share)).status,409);
});
